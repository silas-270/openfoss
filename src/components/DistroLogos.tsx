/**
 * DistroWatermark für Card-Hintergründe
 */
export function DistroWatermark({ id, className = "size-48" }: { id: string; className?: string }) {
  switch (id) {
    case "mint":
      return <MintLogo className={className} />;
    case "ubuntu":
      return <UbuntuLogo className={className} />;
    case "fedora":
      return <FedoraLogo className={className} />;
    case "debian":
      return <DebianLogo className={className} />;
    case "popos":
      return <PoposLogo className={className} />;
    case "zorin":
      return <ZorinLogo className={className} />;
    default:
      return null;
  }
}

